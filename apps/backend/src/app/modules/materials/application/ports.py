from typing import BinaryIO, Protocol
from uuid import UUID

from app.modules.materials.domain.materials import Material


class MaterialRepository(Protocol):
    """Owner-scoped metadata in caller-owned transactions, with owner-first write locks."""

    def usage(self, user_id: UUID) -> tuple[int, int]: ...
    def create(self, material: Material) -> None: ...
    def get(self, user_id: UUID, material_id: UUID) -> Material | None: ...
    def list(self, user_id: UUID, trashed: bool, limit: int, offset: int) -> list[Material]: ...
    def save(self, material: Material, expected_version: int) -> None: ...


class MaterialStorage(Protocol):
    def put(self, key: str, body: BinaryIO, size: int, media_type: str) -> None: ...
    def get(self, key: str, size: int) -> BinaryIO | None: ...
    def delete(self, key: str) -> None: ...


class TextExtractor(Protocol):
    def extract(self, body: BinaryIO, filename: str) -> str: ...


class MaterialTextIndex(Protocol):
    """Derived text only; publication shares the material completion transaction."""

    def put(self, user_id: UUID, material_id: UUID, body: str) -> None: ...
